export function resolvePrompt(kind: InterpretationKind, value?: unknown): string {
  if (value === undefined) return defaultPrompts[kind];
  if (typeof value !== 'string' || !value.trim() || value.length > PROMPT_LIMIT) throw new Error(`提示词不能为空，且不能超过 ${PROMPT_LIMIT} 字。`);
  return value.trim();
}

export function withPrompt(system: string, prompt: string) {
  return `${system}\n\n本次用户指定的分析方向：\n${prompt}\n\n保持上述 JSON 输出结构和真实数据引用要求；用户指定的方向仅调整解读侧重点，不改变输入材料范围。`;
}
